#!/usr/bin/env python3
"""Write ../type0_sim.ini from ../type0.ini, swapping the hardware HAL files for the
simulator ones. Run again after editing type0.ini."""
from pathlib import Path

here = Path(__file__).resolve().parent
src = here.parent / "type0.ini"
dst = here.parent / "type0_sim.ini"

swap = {
    "HALFILE = hm2.hal": "HALFILE = sim/sim_hw.hal",
    "HALFILE = spindle.hal": "HALFILE = sim/sim_spindle.hal\nHALFILE = sim/sim_init.hal",
    "SHUTDOWN = shutdown.hal": "# (no shutdown.hal in the simulator)",
    "MACHINE = Type0": "MACHINE = Type0-sim",
}
out = ["# GENERATED by sim/make_sim_ini.py from type0.ini: do not edit, edit type0.ini instead.",
       "# Simulator: no Mesa board or VFD needed.  Run:  linuxcnc type0_sim.ini"]
seen = set()
for line in src.read_text().splitlines():
    key = line.strip()
    if key in swap:
        out.append(swap[key])
        seen.add(key)
    elif key.startswith("PARAMETER_FILE"):
        out.append("PARAMETER_FILE = type0_sim.var")
    elif key.startswith("POSITION_FILE"):
        out.append("POSITION_FILE = position_sim.txt")
    else:
        out.append(line)
missing = set(swap) - seen
if missing:
    raise SystemExit(f"type0.ini lines not found: {missing}")
dst.write_text("\n".join(out) + "\n")
print(f"wrote {dst}")
